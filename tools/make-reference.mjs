// Records numeric shot inputs ({t, a, b}) + expected hashes for the
// cross-device self-test (v4, 3D camera).
import { readFileSync, writeFileSync } from 'node:fs';
import { initPhysics, replay, Sim } from '../src/sim.js';
import { LEVELS } from '../src/levels.js';
await initPhysics();
const bot = JSON.parse(readFileSync('out/bot-final.json', 'utf8'));
const EVERY = 30;
const cases = [];
for (const e of bot.levels) {
  if (!e.solution || !e.solution.sequence) throw new Error('no solution for B' + e.level);
  cases.push({ name: 'B' + e.level + ' kazanan', level: e.level, mode: '3d', shots: e.solution.sequence });
}
// a miss first, then the known solution (level 10 has a spare normal ball);
// the miss is picked so that the solution still wins afterwards
const b10 = bot.levels.find((x) => x.level === 10).solution.sequence;
const lv10 = LEVELS.find((l) => l.id === 10);
let miss = null;
for (const cand of [{ t: 'normal', a: 150, b: 50 }, { t: 'normal', a: 150, b: 700 }, { t: 'normal', a: 0, b: 50 }, { t: 'normal', a: -150, b: 700 }]) {
  const s = new Sim(lv10, '3d');
  s.runShot(cand.a, cand.b, cand.t);
  const untouched = s.cagesLeft() === lv10.cages.length && s.totemsLeft() === lv10.totems.length && s.nestsBroken() === 0;
  for (const sh of b10) s.runShot(sh.a, sh.b, sh.t);
  const ok = untouched && s.phase === 'won';
  s.free();
  if (ok) { miss = cand; break; }
}
if (!miss) throw new Error('no clean miss found for B10');
cases.push({ name: 'B10 ıska + çözüm', level: 10, mode: '3d', shots: [miss, ...b10] });
// an ember that cracks the nest (protect goal failure path)
const lv8 = LEVELS.find((l) => l.id === 8);
let nestShot = null;
for (let b = 50; b <= 400 && !nestShot; b += 10) {
  const s = new Sim(lv8, '3d');
  s.runShot(0, b, 'ember');
  if (s.nestsBroken() > 0) nestShot = { t: 'ember', a: 0, b };
  s.free();
}
if (nestShot) cases.push({ name: 'B8 yuva kırılır', level: 8, mode: '3d', shots: [nestShot] });
let fxMismatch = 0;
for (const c of cases) {
  const lv = LEVELS.find((l) => l.id === c.level);
  c.expect = replay(lv, c.mode, c.shots, EVERY);
  const sim = new Sim(lv, c.mode, { fx: true });
  for (const s of c.shots) sim.runShot(s.a, s.b, s.t);
  if (sim.hash() !== c.expect.final || sim.step !== c.expect.finalStep) fxMismatch++;
  sim.free();
  console.log(c.name.padEnd(20), JSON.stringify(c.shots), 'phase', c.expect.phase, 'steps', c.expect.finalStep, 'final', c.expect.final);
}
const pkg = JSON.parse(readFileSync('node_modules/@dimforge/rapier3d-deterministic-compat/package.json', 'utf8'));
const meta = { checkpointEvery: EVERY, engine: pkg.name + '@' + pkg.version, recordedOn: 'Node ' + process.version + ' (masaüstü, x86-64)', recordedAt: new Date().toISOString() };
writeFileSync('src/reference.js', '// Generated by tools/make-reference.mjs. Numeric shot inputs and expected state hashes.\nexport const REFERENCE = ' + JSON.stringify({ meta, cases }) + ';\n');
console.log('cases', cases.length, 'fx-vs-nofx mismatches', fxMismatch, 'won', cases.filter((c) => c.expect.phase === 'won').length, 'lost', cases.filter((c) => c.expect.phase === 'lost').length);
