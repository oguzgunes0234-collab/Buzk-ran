// Records numeric shot inputs + expected hashes for the cross-device self-test.
import { readFileSync, writeFileSync } from 'node:fs';
import { initPhysics, replay, Sim } from '../src/sim.js';
import { LEVELS } from '../src/levels.js';
await initPhysics();
const bot = JSON.parse(readFileSync('out/bot-final.json', 'utf8'));
const EVERY = 30;
const cases = [];
const MISS = { '3d': { a: -150, b: 700 }, '25d': { a: 800, b: 25 } };
for (const e of bot.levels) {
  let shots;
  if (e.oneShot.sample) shots = [{ a: e.oneShot.sample.a, b: e.oneShot.sample.b }];
  else if (e.multiShot && e.multiShot.followup && e.multiShot.followup.sample) shots = [...e.multiShot.prefix, { a: e.multiShot.followup.sample.a, b: e.multiShot.followup.sample.b }];
  else throw new Error('no winning sequence for L' + e.level + ' ' + e.mode);
  cases.push({ name: 'B' + e.level + ' ' + (e.mode === '3d' ? '3D' : '2,5D') + ' kazanan', level: e.level, mode: e.mode, shots });
}
for (const mode of ['3d', '25d']) {
  const e = bot.levels.find((x) => x.level === 8 && x.mode === mode);
  cases.push({ name: 'B8 ' + (mode === '3d' ? '3D' : '2,5D') + ' iki ıska + atış', level: 8, mode, shots: [MISS[mode], MISS[mode], { a: e.oneShot.sample.a, b: e.oneShot.sample.b }] });
}
let fxMismatch = 0;
for (const c of cases) {
  const lv = LEVELS.find((l) => l.id === c.level);
  c.expect = replay(lv, c.mode, c.shots, EVERY);
  // the game runs with visual-effect events enabled; they must not change physics
  const sim = new Sim(lv, c.mode, { fx: true });
  for (const s of c.shots) sim.runShot(s.a, s.b);
  if (sim.hash() !== c.expect.final || sim.step !== c.expect.finalStep) fxMismatch++;
  sim.free();
  console.log(c.name.padEnd(26), 'shots', JSON.stringify(c.shots), 'phase', c.expect.phase, 'steps', c.expect.finalStep, 'final', c.expect.final);
}
const pkg = JSON.parse(readFileSync('node_modules/@dimforge/rapier3d-deterministic-compat/package.json', 'utf8'));
const meta = { checkpointEvery: EVERY, engine: pkg.name + '@' + pkg.version, recordedOn: 'Node ' + process.version + ' (masaüstü, x86-64)', recordedAt: new Date().toISOString() };
writeFileSync('src/reference.js', '// Generated by tools/make-reference.mjs. Numeric shot inputs and expected state hashes.\nexport const REFERENCE = ' + JSON.stringify({ meta, cases }) + ';\n');
console.log('cases', cases.length, 'fx-vs-nofx mismatches', fxMismatch, 'won', cases.filter((c) => c.expect.phase === 'won').length);
